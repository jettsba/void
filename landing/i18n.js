window.applyVoidLang = function (lang) {
    const dict = window.VOID_I18N[lang] || window.VOID_I18N.ru;
    document.documentElement.lang = lang;

    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const k = el.getAttribute('data-i18n');
        if (dict[k] != null) el.textContent = dict[k];
    });
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
        const k = el.getAttribute('data-i18n-html');
        if (dict[k] != null) el.innerHTML = dict[k];
    });
    document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
        const spec = el.getAttribute('data-i18n-attr') || '';
        spec.split(';').forEach((pair) => {
            const [attr, key] = pair.split(':').map((s) => s && s.trim());
            if (!attr || !key) return;
            if (dict[key] != null) el.setAttribute(attr, dict[key]);
        });
    });

    document.querySelectorAll('.lang-toggle [data-lang]').forEach((el) => {
        el.classList.toggle('is-active', el.getAttribute('data-lang') === lang);
    });

    try { localStorage.setItem('void.lang', lang); } catch (e) {}
};

window.getVoidLang = function () {
    try {
        const saved = localStorage.getItem('void.lang');
        if (saved === 'ru' || saved === 'en') return saved;
    } catch (e) {}
    return 'ru';
};
